'use strict';

const { FieldValue } = require('firebase-admin/firestore');
const { HttpsError } = require('firebase-functions/v2/https');
const { validId, belongsToWorkspace } = require('./workspace-reset-policy');
const fail = message => { throw new HttpsError('failed-precondition', message); };
const methods = new Set(['pix', 'cash', 'transfer', 'debit_card', 'other']);

function paymentInput(value) {
  if (value == null || value.status === 'pending') return null;
  if (value.status !== 'paid' || !methods.has(value.method)) fail('Escolha uma forma válida de recebimento.');
  return { method: value.method, accountId: validId(value.accountId, 'Conta'), homeId: validId(value.homeId, 'Espaço da conta') };
}

function consignmentFinance(db) {
  const spaceDoc = id => db.doc('financialSpaces/' + id);
  const entry = (c, id) => spaceDoc(c.spaceId).collection('entries').doc('consignment_' + id);

  async function accountFor(tx, c, payment, amount) {
    if (!payment || !amount) return null;
    const home = spaceDoc(payment.homeId);
    const [homeDoc, accountDoc] = await tx.getAll(home, home.collection('financialAccounts').doc(payment.accountId));
    const account = accountDoc.data(), space = homeDoc.data();
    const mode = account?.accessMode || 'single_space';
    const permitted = mode === 'all_spaces' || mode === 'selected_spaces' && account.allowedFinancialSpaceIds?.includes(c.spaceId) ||
      mode === 'single_space' && (account?.defaultFinancialSpaceId || payment.homeId) === c.spaceId;
    if (!belongsToWorkspace(space, c.businessId) || space.active === false || (space.status && space.status !== 'active') || space.capabilities?.finance !== true ||
      space.ownerUid !== c.space.ownerUid || !account || account.active === false || account.ownerUid !== c.space.ownerUid ||
      account.accountHomeSpaceId && account.accountHomeSpaceId !== payment.homeId || !permitted)
      fail('Escolha uma conta ativa e autorizada para este espaço.');
    const balance = account.currentBalanceCents ?? account.initialBalanceCents ?? 0;
    if (!Number.isSafeInteger(balance) || !Number.isSafeInteger(balance + amount)) fail('A conta precisa de conferência de saldo.');
    return { ref: accountDoc.ref, balanceCents: balance + amount, schemaVersion: Math.max(5, Number(account.schemaVersion) || 0), ...payment };
  }

  function paymentFields(account, at, op, periodKey) {
    return account ? { status: 'paid', cashFlowEffect: true, paidAt: at, occurredAt: at, sortAt: at, periodKey,
      paymentMethod: account.method, financialAccountId: account.accountId, financialAccountHomeSpaceId: account.homeId, paymentOperationId: op }
      : { status: 'pending', cashFlowEffect: false, paidAt: null, occurredAt: null, sortAt: at, periodKey,
        paymentMethod: null, financialAccountId: null, financialAccountHomeSpaceId: null };
  }

  function recordEvent(tx, c, ref, account, amount, op, at) {
    if (account) tx.update(account.ref, { currentBalanceCents: account.balanceCents, balanceUpdatedAt: at,
      lastBalanceOperationId: op, schemaVersion: account.schemaVersion, updatedAt: FieldValue.serverTimestamp() });
    const id = 'consignment_' + op;
    tx.create(spaceDoc(c.spaceId).collection('events').doc(id), {
      id, operationId: id, entryId: ref.id, financialSpaceId: c.spaceId, ownerUid: c.space.ownerUid,
      sourceSpaceId: c.spaceId, createdBy: 'system', autoGenerated: true, amountCents: amount,
      eventKind: account ? 'consignment_settled' : 'consignment_receivable_created',
      transition: account ? 'paid' : 'created', status: 'applied', createdAt: at,
    });
  }

  async function prepare(tx, c, amount, payment, conferenceId, settlement = false) {
    if (!amount && !settlement) return null;
    if (c.space.capabilities?.finance !== true || !c.space.ownerUid)
      fail('Este espaço precisa do Financeiro habilitado para registrar valores de consignação.');
    const ref = entry(c, conferenceId), snap = await tx.get(ref), current = snap.data();
    if (!settlement && snap.exists) fail('Já existe um lançamento financeiro para esta conferência.');
    if (settlement && (!current || current.status !== 'pending' || current.sourceType !== 'consignment_receivable' ||
      current.sourceId !== conferenceId || current.financialSpaceId !== c.spaceId ||
      current.linkedBusinessId !== c.businessId || current.workspaceGeneration !== c.workspaceGeneration ||
      !Number.isSafeInteger(current.amountCents) || current.amountCents <= 0))
      fail('O acerto já foi confirmado ou o lançamento precisa de conferência.');
    amount = settlement ? current.amountCents : amount;
    const account = await accountFor(tx, c, payment, amount);
    if (settlement && !account) fail('Selecione a conta que recebeu o acerto.');
    return { ref, account, amount, settlement, conferenceId };
  }

  function apply(tx, c, f, history, at) {
    if (!f) return;
    const { ref, account, amount, settlement, conferenceId } = f;
    const periodKey = history.deliveredOn.slice(0, 7);
    const fields = { ...paymentFields(account, at, 'consignment_' + history.id, periodKey), updatedAt: FieldValue.serverTimestamp() };
    if (settlement) tx.update(ref, fields);
    else tx.create(ref, {
      id: ref.id, operationId: ref.id, idempotencyKey: c.spaceId + ':' + ref.id, schemaVersion: 2, autoGenerated: true,
      financialSpaceId: c.spaceId, sourceSpaceId: c.spaceId, financialRoutingVersion: 2, spaceType: c.space.type || 'business',
      linkedBusinessId: c.businessId, workspaceGeneration: c.workspaceGeneration, ownerUid: c.space.ownerUid, createdBy: 'system',
      direction: 'in', entryType: 'automatic_income', sourceType: 'consignment_receivable', sourceId: conferenceId, currency: 'BRL',
      amountCents: amount, description: 'Consignação · ' + history.outlet.name, categoryId: 'default_business_sales',
      categoryName: 'Vendas', categoryIcon: 'badge-dollar-sign', subcategoryName: 'Consignação', categorySchemaVersion: 2,
      dueAt: at, duePeriodKey: periodKey, createdAt: at, ...fields,
    });
    recordEvent(tx, c, ref, account, amount, history.id, at);
  }
  return { entry, prepare, apply };
}

module.exports = { consignmentFinance, paymentInput };
